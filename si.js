  function artifactEntries(artifact) {
    const ext = (String(artifact.name).split('.').pop() || '').toLowerCase();
    if (['zip', 'apk', 'jar', 'aab'].includes(ext)) return window.SRTFiles.parseFileSections(artifact.body);
    return [{ path: artifact.name, content: artifact.body }];
  }

  function downloadEntry(entry) {
    const name = String(entry.path).replace(/[\\/:*?"<>|]/g, '_');
    window.SRTFiles.downloadText(name, entry.content);
  }

